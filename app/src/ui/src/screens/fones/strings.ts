export function fonesLang(): "pt-BR" | "en" {
  const l = typeof navigator !== "undefined" ? navigator.language : "en";
  return l.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

export function ft(key: Key, ...args: (string | number)[]): string {
  const s = (fonesLang() === "pt-BR" ? ptBR : en)[key];
  return args.length ? printf(s, args) : s;
}
